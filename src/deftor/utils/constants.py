DEFAULT_OUTPUT_DIR = Path.cwd() / "analyses"
STATISTIC_LOG_FILENAME = "statistics.csv"
STATISTIC_LOG_PATH = Path.cwd() / STATISTIC_LOG_FILENAME

# One row per run. Per-item data lives in the analysis output files.
STATISTIC_LOG_FIELDS = [
    # Unique hex id (uuid4) generated per run; distinguishes individual rows.
    "run_id",
    # UTC ISO-8601 timestamp of when the run's statistics were assembled.
    "timestamp",
    # Backend that ran the analysis: "ollama" or "huggingface".
    "backend",
    # Model name/id exactly as passed to deftor (--model).
    "model",
    # Media type analyzed: "image", "audio", "video" or "text".
    "media_type",
    # Grouping label for the dataset (--dataset); empty when not given.
    "dataset",
    # Path of the labels file used for scoring (--labels); empty when not given.
    "labels_file",
    # Label value treated as the positive/DEEPFAKE class in metrics (--positive-label).
    "positive_label",
    # Total number of input items handed to the model.
    "number_of_items",
    # Items that produced a valid response (success == True).
    "number_succeeded",
    # Items that errored or failed response validation.
    "number_failed",
    # Wall-clock seconds for the whole run (for HF, model loading is excluded).
    "total_execution_time",
    # Seconds spent loading the HF pipeline; empty for Ollama (loads server-side).
    "model_loading_time",
    # Mean per-item execution time, in seconds (failed attempts included).
    "mean_item_execution_time",
    # 95th percentile (nearest-rank) of per-item execution times, in seconds.
    "p95_item_execution_time",
    # Items processed per second: number_of_items / total_execution_time.
    "throughput_items_per_sec",
    # Ollama-native timings/token counts, empty for other backends.
    # Server-reported total time for that request, in nanoseconds.
    "total_duration_ns",
    # Server-reported time to load the model for that request, in nanoseconds.
    "load_duration_ns",
    # Number of tokens in the evaluated prompt.
    "prompt_eval_count",
    # Number of tokens generated by the model.
    "eval_count",
    # Server-reported time spent generating tokens, in nanoseconds.
    "eval_duration_ns",
]

